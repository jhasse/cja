def test_reuse_from(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    source_dir = tmp_path / "src"
    _write_project(
        source_dir,
        "add_library(base STATIC base.cpp)\n"
        "target_precompile_headers(base PRIVATE pch.h)\n"
        "add_executable(app main.cpp)\n"
        "target_precompile_headers(app REUSE_FROM base)\n"
        "get_target_property(headers base PRECOMPILE_HEADERS)\n"
        'message(STATUS "headers=${headers}")\n',
    )
    (source_dir / "base.cpp").write_text("int f() { return 0; }\n")
    (source_dir / "main.cpp").write_text("int main() { return 0; }\n")

    configure(source_dir, "build")

    app_wrapper = (source_dir / "build/CMakeFiles/app.dir/cmake_pch.hxx").read_text()
    assert f'#include "{source_dir / "pch.h"}"' in app_wrapper
    assert f"headers={source_dir / 'pch.h'}" in capsys.readouterr().out


def test_pch_build_end_to_end(tmp_path: Path) -> None:
    """Sources only compile if the precompiled header was force-included."""
    source_dir = tmp_path / "src"
    _write_project(
        source_dir,
        "add_executable(app main.cpp util.c)\n"
        "target_precompile_headers(app PRIVATE pch.h)\n",
    )
    (source_dir / "pch.h").write_text("#define ANSWER 42\n")
    (source_dir / "util.c").write_text("int answer(void) { return ANSWER; }\n")
    (source_dir / "main.cpp").write_text(
        'extern "C" int answer(void);\n'
        "int main() { return answer() == ANSWER ? 0 : 1; }\n"
    )

    result = subprocess.run(
        [sys.executable, "-m", "cja", "run"],
        capture_output=True,
        text=True,
        cwd=source_dir,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    assert (source_dir / "build/CMakeFiles/app.dir/cmake_pch.hxx.gch").exists()
    assert (source_dir / "build/CMakeFiles/app.dir/cmake_pch.h.gch").exists()
